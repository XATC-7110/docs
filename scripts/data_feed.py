def replace_block(page_text: str, block: str) -> str:
    """Put block between the markers, leaving everything outside them as it was."""
    if page_text.count(MARK_BEGIN) != 1 or page_text.count(MARK_END) != 1:
        raise SummaryError([f"{BLOCK_PAGE} must hold exactly one {MARK_BEGIN} and one {MARK_END}"])
    start = page_text.index(MARK_BEGIN)
    end = page_text.index(MARK_END)
    if end < start:
        raise SummaryError([f"{MARK_END} comes before {MARK_BEGIN} in {BLOCK_PAGE}"])
    inner = f"\n\n{GENERATED_NOTE}\n\n{block}\n\n"
    return page_text[:start] + MARK_BEGIN + inner + page_text[end:]


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def run(summary_text: str | None, root: Path = REPO, force: bool = False) -> dict:
    """Render and write the generated files. summary_text None renders again what is stored (or the
    stand-in sentences when nothing is). Nothing is written unless everything rendered."""
    stored, stored_baseline = load_store(root)
    if summary_text is None:
        summary, previous = stored, stored_baseline
    else:
        summary = parse_summary(summary_text)
        if stored is not None and summary["effective"] < stored["effective"] and not force:
            raise SummaryError([f"effective {summary['effective']} is older than the stored summary's "
                                f"{stored['effective']}; give --force (or DATA_FEED_FORCE=1) to write it anyway"])
        previous = baseline_for(summary, stored, stored_baseline)
    out = render_pages(root, summary, previous)
    page = replace_block((root / BLOCK_PAGE).read_text(encoding="utf-8"), out["block"])
    write_text(root / BLOCK_PAGE, page)
    write_text(root / GAPS_PAGE, out["gaps"])
    if out["store"] is not None:
        write_text(root / STORE, out["store"])
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("summary", help="the summary JSON file")
    ap.add_argument("--root", type=Path, default=REPO, help="the repository to write into")
    ap.add_argument("--changes-file", type=Path, help="write the marked changes (Markdown) here")
    ap.add_argument("--force", action="store_true",
                    help="accept a summary whose effective date is older than the stored one (or DATA_FEED_FORCE=1)")
    ap.add_argument("--github-output", type=Path, help="append cycle= and release= lines here (a GITHUB_OUTPUT file)")
    args = ap.parse_args(argv)
    try:
        text = Path(args.summary).read_text(encoding="utf-8")
        out = run(text, args.root, force=args.force or os.environ.get("DATA_FEED_FORCE") == "1")
    except SummaryError as exc:
        print("The summary was refused, nothing was written:", file=sys.stderr)
        for problem in exc.problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1
    summary = json.loads(text)
    if args.changes_file:
        write_text(args.changes_file, out["changes"])
    if args.github_output:
        with open(args.github_output, "a", encoding="utf-8") as handle:
            handle.write(f"cycle={summary['cycle']}\nrelease={summary['release']}\n")
    print(out["r"].what_changed())
    return 0


if __name__ == "__main__":
    sys.exit(main())
