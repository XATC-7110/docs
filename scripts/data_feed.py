#!/usr/bin/env python3
"""The data feed (SOT-212, parent SOT-209): turns a summary of the live FAA release into pages of this site.

The data tool computes the summary (format 1, see SUMMARY_KEYS below) and starts the workflow
.github/workflows/data-feed.yml, which runs this script and opens a pull request. The words are in
scripts/templates/data-feed.md.tmpl: edit them there, not in the generated files.

    python scripts/data_feed.py SUMMARY.json [--root DIR] [--changes-file PATH] [--github-output PATH]

It writes three files under the root (default: this repository):
  docs/known-limitations.md    the block between the data-feed markers is replaced; the rest is untouched
  docs/data-gaps.md            the full lists (generated; capped at 500 rows per list)
  docs/_generated/data-feed.json   the summary, and the one it was compared with, for the next run

Marks ("new since 2610") are always against the summary stored by the previous feed, so they fade after
the next feed. A summary whose effective date is older than the stored one is refused unless --force
(or DATA_FEED_FORCE=1) is given.

The same summary twice gives byte-identical files: the stored file keeps the summary that the stored
one was compared with, and a repeat of the stored summary is compared with that instead of with itself.

The repository is public. The summary holds only what the FAA publishes and counts of our own build; the
script refuses any string that names a third-party data source or a cloud service, and our own phrasing and
the missing-approach reasons may not hold a word the site never uses.
Standard library only.
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
import re
import string
import unicodedata
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TEMPLATE_PATH = Path("scripts/templates/data-feed.md.tmpl")
BLOCK_PAGE = Path("docs/known-limitations.md")
GAPS_PAGE = Path("docs/data-gaps.md")
STORE = Path("docs/_generated/data-feed.json")

MARK_BEGIN = "<!-- data-feed:begin -->"
MARK_END = "<!-- data-feed:end -->"
GENERATED_NOTE = "<!-- Generated by scripts/data_feed.py; edit the template, not this file -->"

MAX_CHARS = 60_000          # the workflow input's limit, kept under GitHub's 65,535
MAX_ROWS = 500              # rows shown per list on the gaps page

# Strings are refused when they hold any of these (case-insensitive, after NFKC normalisation). The first
# group is third-party data sources: the docs repository is public and the product uses FAA data only. The
# names are put together here so that this source does not spell them. The second is words the site never
# uses in its own voice (AGENTS.md); it applies to our own phrasing and to the reasons, not to the FAA's
# airport and chart names. The third is cloud services, which the site never names.
_FRAGMENTS = (("sim", "aware"), ("tracon", "_", "boundaries"), ("tracon", "-", "boundaries"),
              ("tracon", " ", "boundaries"), ("vat", "sim"), ("iv", "ao"), ("pilot", "edge"), ("navi", "graph"),
              ("jepp", "esen"), ("open", "street", "map"), ("our", "airports"), ("flight", "aware"),
              ("adsb", "exchange"), ("open", "sky"))
THIRD_PARTY = tuple("".join(parts) for parts in _FRAGMENTS)
NOT_PILOT_WORDS = ("xatc", "gateway", "training")
CLOUD = re.compile(r"\baws\b|\bs3\b|amazon|cloudfront|route ?53|dynamodb|\blambda\b|bedrock", re.I)
# The text fields (names, runways, approach names, reasons) may hold only these characters.
TEXT_CHARS = r"[A-Za-z0-9 .\-/'&,()#+]+"

SUMMARY_KEYS = ("format", "generated", "release", "cycle", "effective", "approaches", "airports", "lists", "fixes")
APPROACH_INTS = ("published", "coded_by_faa", "built_by_us", "missing")
AIRPORT_INTS = ("total", "all_available", "some_missing", "runway_without_approach", "circling_only_missing")
LIST_NAMES = ("runway_without_approach", "circling_only_missing", "some_missing")
FIX_KEYS = ("total", "confirmed", "lexicon_version", "lexicon_generated")

MAX_LIST_ENTRIES = 5000
MAX_REASONS = 30


class SummaryError(ValueError):
    """The summary is not acceptable; .problems lists every reason."""

    def __init__(self, problems: list[str]):
        super().__init__("; ".join(problems))
        self.problems = problems


# ---------------------------------------------------------------- validation

def forbidden_in(text: str, pilot_words: bool = True) -> str | None:
    """The first forbidden word found in text, or None. pilot_words False leaves out the words the site
    does not use in its own voice (airport and chart names may hold them)."""
    norm = unicodedata.normalize("NFKC", text)
    low = norm.lower()
    compact = re.sub(r"[^a-z0-9]", "", low)
    for word in THIRD_PARTY:
        if word in low or (len(word) >= 7 and re.sub(r"[^a-z0-9]", "", word) in compact):
            return word
    if pilot_words:
        for word in NOT_PILOT_WORDS:
            if word in low:
                return word
    m = CLOUD.search(norm)
    return m.group(0) if m else None


def _is_int(value) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _string(value, where: str, errs: list[str], max_len: int, pattern: str | None = None,
            pilot_words: bool = True) -> None:
    if not isinstance(value, str):
        errs.append(f"{where}: must be a string")
        return
    if not value or value != value.strip():
        errs.append(f"{where}: must not be empty or start or end with a space")
        return
    if len(value) > max_len:
        errs.append(f"{where}: longer than {max_len} characters")
    if any(ord(c) < 32 or ord(c) == 127 for c in value):
        errs.append(f"{where}: must not hold control characters or line breaks")
    if pattern and not re.fullmatch(pattern, value):
        errs.append(f"{where}: not in the expected form")
    word = forbidden_in(value, pilot_words)
    if word:
        errs.append(f"{where}: holds a word that must not be on this site ({word!r})")


def _date(value, where: str, errs: list[str]) -> None:
    if not isinstance(value, str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
        errs.append(f"{where}: must be a date written YYYY-MM-DD")
        return
    try:
        datetime.date.fromisoformat(value)
    except ValueError:
        errs.append(f"{where}: not a real date")


def _count(value, where: str, errs: list[str]) -> None:
    if not _is_int(value) or value < 0 or value > 10**9:
        errs.append(f"{where}: must be a whole number, zero or more")


def _exact_keys(obj, keys: tuple[str, ...], where: str, errs: list[str]) -> bool:
    if not isinstance(obj, dict):
        errs.append(f"{where}: must be an object")
        return False
    for k in obj:
        if k not in keys:
            errs.append(f"{where}: unknown key {k!r}")
    for k in keys:
        if k not in obj:
            errs.append(f"{where}: missing key {k!r}")
    return all(k in obj for k in keys) and all(k in keys for k in obj)


def _string_list(value, where: str, errs: list[str], max_items: int, max_len: int) -> None:
    """A list of names from the FAA: the character list applies, the pilot-word list does not."""
    if not isinstance(value, list):
        errs.append(f"{where}: must be a list")
        return
    if len(value) > max_items:
        errs.append(f"{where}: more than {max_items} items")
    for i, item in enumerate(value[:max_items]):
        _string(item, f"{where}[{i}]", errs, max_len, TEXT_CHARS, pilot_words=False)


def validate_summary(summary) -> None:
    """Raise SummaryError unless summary is a well-formed format 1 summary."""
    errs: list[str] = []
    if not _exact_keys(summary, SUMMARY_KEYS, "summary", errs):
        raise SummaryError(errs)
    if not _is_int(summary["format"]) or summary["format"] != 1:
        errs.append("format: must be the whole number 1")
    _date(summary["generated"], "generated", errs)
    _date(summary["effective"], "effective", errs)
    _string(summary["cycle"], "cycle", errs, 4, r"\d{4}")
    _string(summary["release"], "release", errs, 8, r"\d{4}(r\d{1,3})?")
    if isinstance(summary["release"], str) and isinstance(summary["cycle"], str) \
            and not summary["release"].startswith(summary["cycle"]):
        errs.append("release: must start with the cycle")

    ap = summary["approaches"]
    if _exact_keys(ap, APPROACH_INTS + ("missing_by_reason",), "approaches", errs):
        for k in APPROACH_INTS:
            _count(ap[k], f"approaches.{k}", errs)
        if all(_is_int(ap[k]) for k in APPROACH_INTS) and \
                ap["published"] != ap["coded_by_faa"] + ap["built_by_us"] + ap["missing"]:
            errs.append("approaches: published must equal coded_by_faa + built_by_us + missing")
        reasons = ap["missing_by_reason"]
        if not isinstance(reasons, list):
            errs.append("approaches.missing_by_reason: must be a list")
        else:
            if len(reasons) > MAX_REASONS:
                errs.append(f"approaches.missing_by_reason: more than {MAX_REASONS} reasons")
            seen = set()
            for i, item in enumerate(reasons[:MAX_REASONS]):
                where = f"approaches.missing_by_reason[{i}]"
                if _exact_keys(item, ("reason", "count"), where, errs):
                    _string(item["reason"], f"{where}.reason", errs, 120, TEXT_CHARS)
                    _count(item["count"], f"{where}.count", errs)
                    if isinstance(item["reason"], str):
                        if item["reason"] in seen:
                            errs.append(f"{where}.reason: given twice")
                        seen.add(item["reason"])

    air = summary["airports"]
    if _exact_keys(air, AIRPORT_INTS, "airports", errs):
        for k in AIRPORT_INTS:
            _count(air[k], f"airports.{k}", errs)
        if all(_is_int(air[k]) for k in AIRPORT_INTS) and air["total"] != sum(air[k] for k in AIRPORT_INTS[1:]):
            errs.append("airports: total must equal all_available + some_missing + runway_without_approach "
                        "+ circling_only_missing")

    lists = summary["lists"]
    if _exact_keys(lists, LIST_NAMES, "lists", errs):
        for name in LIST_NAMES:
            entries = lists[name]
            if not isinstance(entries, list):
                errs.append(f"lists.{name}: must be a list")
                continue
            if len(entries) > MAX_LIST_ENTRIES:
                errs.append(f"lists.{name}: more than {MAX_LIST_ENTRIES} airports")
            seen = set()
            for i, item in enumerate(entries[:MAX_LIST_ENTRIES]):
                where = f"lists.{name}[{i}]"
                if not _exact_keys(item, ("id", "name", "runways", "missing"), where, errs):
                    continue
                _string(item["id"], f"{where}.id", errs, 6, r"[A-Z0-9]{2,6}")
                _string(item["name"], f"{where}.name", errs, 100, TEXT_CHARS, pilot_words=False)
                _string_list(item["runways"], f"{where}.runways", errs, 40, 12)
                _string_list(item["missing"], f"{where}.missing", errs, 60, 80)
                if isinstance(item["id"], str):
                    if item["id"] in seen:
                        errs.append(f"{where}.id: {item['id']!r} is in the list twice")
                    seen.add(item["id"])

    fixes = summary["fixes"]
    if _exact_keys(fixes, FIX_KEYS, "fixes", errs):
        for k in ("total", "confirmed", "lexicon_version"):
            _count(fixes[k], f"fixes.{k}", errs)
        _date(fixes["lexicon_generated"], "fixes.lexicon_generated", errs)
        if _is_int(fixes["total"]) and _is_int(fixes["confirmed"]) and fixes["confirmed"] > fixes["total"]:
            errs.append("fixes.confirmed: more than fixes.total")
    if errs:
        raise SummaryError(errs)


def parse_summary(text: str) -> dict:
    """Parse and validate the summary text (the workflow input)."""
    if len(text) > MAX_CHARS:
        raise SummaryError([f"the summary is {len(text)} characters; the limit is {MAX_CHARS}"])
    try:
        summary = json.loads(text)
    except ValueError as exc:
        raise SummaryError([f"not JSON: {exc}"]) from exc
    validate_summary(summary)
    return summary


# ---------------------------------------------------------------- the stored file

def dump_json(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def load_store(root: Path) -> tuple[dict | None, dict | None]:
    """(stored summary, the summary it was compared with), or (None, None) when nothing is stored."""
    path = root / STORE
    if not path.exists():
        return None, None
    try:
        stored = json.loads(path.read_text(encoding="utf-8"))
    except ValueError as exc:
        raise SummaryError([f"{STORE} is not JSON: {exc}"]) from exc
    errs: list[str] = []
    if not _exact_keys(stored, ("format", "summary", "compared_with"), str(STORE), errs):
        raise SummaryError(errs)
    validate_summary(stored["summary"])
    if stored["compared_with"] is not None:
        validate_summary(stored["compared_with"])
    return stored["summary"], stored["compared_with"]


def baseline_for(summary: dict, stored: dict | None, stored_baseline: dict | None) -> dict | None:
    """The summary to compare with: the stored one, or what the stored one was compared with when the
    same summary arrives again (so a repeat writes the same pages)."""
    if stored is None:
        return None
    return stored_baseline if stored == summary else stored


# ---------------------------------------------------------------- the template

def load_template(root: Path) -> tuple[dict[str, string.Template], dict[str, string.Template]]:
    sections: dict[str, list[str]] = {}
    current = None
    for line in (root / TEMPLATE_PATH).read_text(encoding="utf-8").split("\n"):
        m = re.fullmatch(r"=== ([a-z_]+) ===", line)
        if m:
            current = m.group(1)
            sections[current] = []
        elif current is not None:
            sections[current].append(line)
    texts = {k: string.Template("\n".join(v).strip("\n")) for k, v in sections.items() if k != "phrases"}
    phrases: dict[str, string.Template] = {}
    for line in sections.get("phrases", []):
        if not line.strip():
            continue
        name, sep, words = line.partition(" = ")
        if not sep:
            raise SummaryError([f"{TEMPLATE_PATH}: a phrases line must read 'name = words': {line!r}"])
        phrases[name.strip()] = string.Template(words.strip())
    # Our own phrasing may not hold a word the site never uses (the FAA's airport and chart names are not ours).
    for name, text in list(texts.items()) + list(phrases.items()):
        word = forbidden_in(text.template)
        if word:
            raise SummaryError([f"{TEMPLATE_PATH}: {name!r} holds a word that must not be on this site ({word!r})"])
    for need in ("block", "gaps", "first", "first_page"):
        if need not in texts:
            raise SummaryError([f"{TEMPLATE_PATH}: missing the section {need!r}"])
    return texts, phrases


# ---------------------------------------------------------------- comparing

def since_label(summary: dict, previous: dict) -> str:
    """What the marks say: the previous cycle, or its release when the cycle is the same."""
    if previous["cycle"] != summary["cycle"]:
        return previous["cycle"]
    if previous["release"] != summary["release"]:
        return previous["release"]
    return previous["generated"]


def compare_lists(summary: dict, previous: dict | None) -> dict:
    """Marks per airport. marks[list][id] is 'new' or 'changed' (absent when unchanged); 'fixed' holds the
    airports that were on a list before and are on neither now, as (list it was on, entry)."""
    marks = {name: {} for name in LIST_NAMES}
    fixed: list[tuple[str, dict]] = []
    if previous is None:
        return {"marks": marks, "fixed": fixed}
    old = {name: {e["id"]: e for e in previous["lists"][name]} for name in LIST_NAMES}
    old_ids = set().union(*(set(old[n]) for n in LIST_NAMES))
    now_ids = set()
    for name in LIST_NAMES:
        for entry in summary["lists"][name]:
            now_ids.add(entry["id"])
            before = old[name].get(entry["id"])
            if before is None:
                marks[name][entry["id"]] = "changed" if entry["id"] in old_ids else "new"
            elif before != entry:
                marks[name][entry["id"]] = "changed"
    for name in LIST_NAMES:
        for entry in previous["lists"][name]:
            if entry["id"] not in now_ids:
                fixed.append((name, entry))
    fixed.sort(key=lambda pair: (pair[1]["id"], pair[0]))
    return {"marks": marks, "fixed": fixed}


def airport_change_counts(summary: dict, cmp: dict) -> dict:
    new_ids, changed_ids = set(), set()
    for name in LIST_NAMES:
        for airport, mark in cmp["marks"][name].items():
            (new_ids if mark == "new" else changed_ids).add(airport)
    changed_ids -= new_ids
    return {"new": len(new_ids), "fixed": len({e["id"] for _, e in cmp["fixed"]}), "changed": len(changed_ids),
            "new_ids": sorted(new_ids), "fixed_ids": sorted({e["id"] for _, e in cmp["fixed"]}),
            "changed_ids": sorted(changed_ids)}


# ---------------------------------------------------------------- rendering

_MD_SPECIAL = re.compile(r"([\\`*_\[\]<>|~#])")


def esc(text: str) -> str:
    """Make text safe inside a Markdown line or table cell."""
    return _MD_SPECIAL.sub(r"\\\1", text).replace("&", "&amp;")


def missing_airports(air: dict) -> int:
    """Airports missing at least one approach: the three kinds together."""
    return air["some_missing"] + air["runway_without_approach"] + air["circling_only_missing"]


def num(n: int) -> str:
    return f"{n:,}"


class Renderer:
    def __init__(self, texts, phrases, summary: dict, previous: dict | None):
        self.texts, self.phrases = texts, phrases
        self.s, self.prev = summary, previous
        self.cmp = compare_lists(summary, previous)
        self.counts = airport_change_counts(summary, self.cmp) if previous else None
        self.since = since_label(summary, previous) if previous else None

    def phrase(self, name: str, **values) -> str:
        return self.phrases[name].substitute(**values)

    def delta(self, now: int, before: int | None) -> str:
        """' (up 200 since 2610)' or '' when nothing moved or there is nothing to compare with."""
        if before is None or now == before:
            return ""
        word = "up_since" if now > before else "down_since"
        return " (" + self.phrase(word, n=num(abs(now - before)), since=self.since) + ")"

    def airports(self, n: int) -> str:
        return self.phrase("airport_one" if n == 1 else "airport_many", n=num(n))

    # -- the sentence about what changed
    def what_changed(self) -> str:
        if self.prev is None:
            return ""      # nothing to compare with: pilots are told nothing
        c = self.counts
        fix_delta = self.s["fixes"]["confirmed"] - self.prev["fixes"]["confirmed"]
        if not (c["new"] or c["fixed"] or c["changed"] or fix_delta):
            return self.phrase("changed_none", since=self.since)
        if fix_delta > 0:
            fix_change = self.phrase("fix_change_up", n=num(fix_delta))
        elif fix_delta < 0:
            fix_change = self.phrase("fix_change_down", n=num(-fix_delta))
        else:
            fix_change = self.phrase("fix_change_same")
        return self.phrase("changed_some", since=self.since, new_airports=self.airports(c["new"]),
                           fixed_airports=self.airports(c["fixed"]), changed_airports=self.airports(c["changed"]),
                           fix_change=fix_change)

    # -- the short block
    def block(self) -> str:
        s, p = self.s, self.prev
        ap, air, fx = s["approaches"], s["airports"], s["fixes"]
        prev_reason = {r["reason"]: r["count"] for r in p["approaches"]["missing_by_reason"]} if p else {}
        lines = []
        for r in ap["missing_by_reason"]:
            before = (prev_reason.get(r["reason"], 0) if p else None)
            lines.append(self.phrase("reason_line", reason=esc(r["reason"]), count=num(r["count"]))
                         + self.delta(r["count"], before))
        airports_change = ""
        missing_now = missing_airports(air)
        if p and missing_now != missing_airports(p["airports"]):
            before = missing_airports(p["airports"])
            airports_change = " " + self.phrase("airports_change_up" if missing_now > before else "airports_change_down",
                                                n=num(abs(missing_now - before)), since=self.since)
        fixes_change = ""
        if p and fx["confirmed"] != p["fixes"]["confirmed"]:
            up = fx["confirmed"] > p["fixes"]["confirmed"]
            fixes_change = " " + self.phrase("fixes_change_up" if up else "fixes_change_down",
                                             n=num(abs(fx["confirmed"] - p["fixes"]["confirmed"])), since=self.since)
        text = self.texts["block"].substitute(
            cycle=esc(s["cycle"]), effective=s["effective"], generated=s["generated"],
            published=num(ap["published"]), coded_by_faa=num(ap["coded_by_faa"]), built_by_us=num(ap["built_by_us"]),
            missing=num(ap["missing"]) + self.delta(ap["missing"], p["approaches"]["missing"] if p else None),
            reasons_intro=(" " + self.phrase("reasons_intro")) if lines else "",
            reasons="\n".join(lines),
            airports_total=num(air["total"]), all_available=num(air["all_available"]),
            missing_airports=num(missing_now), some_missing=num(air["some_missing"]),
            runway_without_approach=num(air["runway_without_approach"]),
            circling_only_missing=num(air["circling_only_missing"]), airports_change=airports_change,
            fixes_confirmed=num(fx["confirmed"]), fixes_total=num(fx["total"]),
            lexicon_version=num(fx["lexicon_version"]), lexicon_generated=fx["lexicon_generated"],
            fixes_change=fixes_change, what_changed=self.what_changed())
        return text

    # -- the tables
    def table(self, name: str) -> str:
        entries = list(self.summary_list(name))
        if not entries:
            return self.phrase("table_none")
        marks = self.cmp["marks"][name]
        entries.sort(key=lambda e: (e["id"] not in marks, e["id"]))   # marked first, then by identifier
        shown, hidden = entries[:MAX_ROWS], entries[MAX_ROWS:]
        show_change = any(e["id"] in marks for e in shown)
        head = ["Airport", "Name", "Runways", "Missing approaches"] + (["Change"] if show_change else [])
        rows = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
        for e in shown:
            cells = [esc(e["id"]), esc(e["name"]), esc(", ".join(e["runways"])), esc(", ".join(e["missing"]))]
            if show_change:
                mark = marks.get(e["id"])
                cells.append(self.phrase(f"{mark}_since", since=self.since) if mark else "")
            rows.append("| " + " | ".join(cells) + " |")
        text = "\n".join(rows)
        if hidden:
            text += "\n\n" + self.phrase("more_rows", n=num(len(hidden))) + "."
        return text

    def summary_list(self, name: str):
        return self.s["lists"][name]

    def fixed_section(self) -> str:
        fixed = self.cmp["fixed"]
        if not fixed:
            return ""
        shown, hidden = fixed[:MAX_ROWS], fixed[MAX_ROWS:]
        was = {"runway_without_approach": self.phrase("no_longer_was_runway"),
               "circling_only_missing": self.phrase("no_longer_was_circling"),
               "some_missing": self.phrase("no_longer_was_some")}
        rows = ["| Airport | Name | Change |", "|---|---|---|"]
        for name, e in shown:
            rows.append("| " + " | ".join([esc(e["id"]), esc(e["name"]),
                                            self.phrase("fixed_since", since=self.since) + f" ({was[name]})"]) + " |")
        text = "\n\n" + self.phrase("no_longer_heading") + "\n\n" + self.phrase("no_longer_intro", since=self.since) \
            + "\n\n" + "\n".join(rows)
        if hidden:
            text += "\n\n" + self.phrase("more_rows", n=num(len(hidden))) + "."
        return text

    def gaps(self) -> str:
        s = self.s
        return self.texts["gaps"].substitute(
            cycle=esc(s["cycle"]), effective=s["effective"], generated=s["generated"],
            what_changed=self.what_changed(),
            runway_without_approach=num(s["airports"]["runway_without_approach"]),
            circling_only_missing=num(s["airports"]["circling_only_missing"]),
            some_missing=num(s["airports"]["some_missing"]),
            runway_table=self.table("runway_without_approach"),
            circling_table=self.table("circling_only_missing"), some_missing_table=self.table("some_missing"),
            fixed_section=self.fixed_section())

    def changes_markdown(self) -> str:
        """The marked changes, for the pull request's description."""
        if self.prev is None:
            return "This is the first summary, so nothing is marked as changed.\n"
        c = self.counts

        def ids(label: str, found: list[str]) -> str:
            if not found:
                return f"- {label}: none\n"
            shown = ", ".join(found[:50]) + (f" and {len(found) - 50} more" if len(found) > 50 else "")
            return f"- {label} ({len(found)}): {shown}\n"

        fix_delta = self.s["fixes"]["confirmed"] - self.prev["fixes"]["confirmed"]
        return (f"Marked changes since {self.since}:\n\n"
                + ids("Newly listed airports", c["new_ids"]) + ids("Fixed airports", c["fixed_ids"])
                + ids("Changed airports", c["changed_ids"])
                + f"- Confirmed fix names: {num(self.s['fixes']['confirmed'])} "
                  f"({'+' if fix_delta >= 0 else '-'}{num(abs(fix_delta))})\n"
                + f"- Approaches missing: {num(self.s['approaches']['missing'])} "
                  f"(was {num(self.prev['approaches']['missing'])})\n")


def tidy(text: str) -> str:
    """No line ends in a space, no more than one blank line in a row, one newline at the end."""
    text = "\n".join(line.rstrip() for line in text.split("\n"))
    return re.sub(r"\n{3,}", "\n\n", text).strip("\n") + "\n"


def render_pages(root: Path, summary: dict | None, previous: dict | None) -> dict:
    """The three generated texts: the block, the gaps page and the stored file. With no summary, the
    stand-in sentences."""
    texts, phrases = load_template(root)
    if summary is None:
        block = texts["first"].substitute()
        gaps = GENERATED_NOTE + "\n\n" + texts["first_page"].substitute()
        out = {"block": tidy(block).rstrip("\n"), "gaps": tidy(gaps), "store": None, "changes": "", "r": None}
    else:
        r = Renderer(texts, phrases, summary, previous)
        out = {"block": tidy(r.block()).rstrip("\n"), "gaps": tidy(GENERATED_NOTE + "\n\n" + r.gaps()),
               "store": dump_json({"format": 1, "summary": summary, "compared_with": previous}),
               "changes": r.changes_markdown(), "r": r}
    for name in ("block", "gaps"):
        word = forbidden_in(out[name], pilot_words=False)   # the template and the reasons were checked on their own
        if word:
            raise SummaryError([f"the generated {name} text holds a word that must not be on this site ({word!r})"])
    return out


